import os

import sentry_sdk
from sentry_sdk.integrations.argv import ArgvIntegration

from sentry_bridge import get_sentry_options  # generated by CI


def before_send(event, hint):
    return event


sentry_sdk.init(
    **get_sentry_options(
        "api",
        os.environ.get("APP_ENV", "production"),
        os.environ.get("SENTRY_DSN"),
        # Optional: callbacks and integrations that can't live in the YAML.
        before_send=before_send,
        integrations=[ArgvIntegration()],
    )
)
